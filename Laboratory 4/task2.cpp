#include <iostream>

int main() {
    int choise {}; // Инициализирую переменную выбора типа перевода температуры
    double temperature {}, result {}; // Инициализирую переменные вводимой температуры и результата

    // ---------------------Вывожу приглашение и инструкции к вводу---------------------
    std::cout << "Здравствуйте! Вы в конвертере температуры, пожалуйста, выберите режим перевода температуры:" << "\n";
    std::cout << "Введите 1, если °C→°F" << "\n" << "Введите 2, если °F→°C" << "\n" << "Введите 3, если °C→K" << "\n" << "Введите 4, если K→°C" << std::endl;
   
    std::cin >> choise; // Принимаю выбор варианта меню

    std::cout << "Пожалуйста, введите значение температуры" << std::endl; // Приглашаю ввести значение температуры, а затем его сохраняю
    std::cin >> temperature;

    switch (choise) { // В конструкции switch по порядку проверяю допустимые значения и в зависимости от этого значения, выполняю формулу
        case 1:
            std::cout << "\n" << "Отлично! Переводим из °C в °F." << std::endl;
            result = temperature * 9.0 / 5.0 + 32.0;
            std::cout << "Ваша температура в °F = " << result << std::endl;
            break;
        case 2:
            std::cout << "\n" << "Отлично! Переводим из °F в °C." << std::endl;
            result = (temperature - 32.0) * 5.0 / 9.0;
            std::cout << "Ваша температура в °C = " << result << std::endl;
            break;
        case 3:
            std::cout << "\n" << "Отлично! Переводим из °C в K." << std::endl;
            result = temperature + 273.15;
            std::cout << "Ваша температура в K = " << result << std::endl;
            break;
        case 4:
            std::cout << "\n" << "Отлично! Переводим из K в °C." << std::endl;
            result = temperature - 273.15;
            std::cout << "Ваша температура в °C = " << result << std::endl;
            break;
        default:
            std::cout << "❌️ Возникла ошибка! Вы ввели не верное число варианта выбора перевода температуры!" << std::endl; // Если ввели что-то другое, то выдаю ошибку
            return 1;
    }
}