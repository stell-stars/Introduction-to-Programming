// =========================================== Программа Авторизации ===========================================
bool authorization(string usr_lgn="", string usr_pssw=""){
    // --------------------- Инициализирую переменные паролей и логинов
    const string def_login {"def"}, def_pass {"123"}; 
    string input_login {""}, input_pass {""}; 

    // --------------------- Выполняю цикл с 3 попытками для проверки логинов и паролей
    int i {3};
    while (i > 0){
        cout << "Введите логин: ";
        cin >> input_login;
        cout << "Введите пароль: ";
        cin >> input_pass;
        cout << endl;

        if ((input_login == def_login || input_login == usr_lgn) && (input_pass == def_pass || input_pass == usr_pssw)) { // Совпадает?+
            cout << "Отлично! Вы успешно вошли в свою учётную запись: " << input_login << endl;
            return true; // Возвращаю истину, так как логин и пароль совпали
        } else {
            i = i - 1;
            cout << "\n" << "Неправильный логин или пароль." << "\n" << "Осталось попыток: " << i << "\n" << endl; // Что-то не совпало! Попытка потратилась
        }
    }
    cout << "\n" << "❌️ Ошибка! Вы не сумели пройти авторизацию: количество попыток закончилось!" << endl;
    return false; // Возвращаю ложь, так как не совпали за 3 попытки пароли и логины
}


