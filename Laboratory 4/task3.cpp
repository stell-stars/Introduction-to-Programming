#include <iostream>
#include <string> // Библиотека для строк

using namespace std;

// =========================================== Подпрограмма Калькулятор ===========================================
void calculator() {

    // --------------------- Инициализирую 3 переменные в своих типах данных
    double num1 {}, num2 {};
    char op {}; 
    
    cout << "=============== Калькулятор ===============" << endl;
    cout << "Введите следующие символы, чтобы выполнить ту или иную операцию:" << "\n" << "> Введите: +, -, *, /" << "\n" << "> Введите q - чтобы вернуться в главное меню" << endl;
    cin >> op;

    // Проверка на выход
    if (op == 'q' || op == 'Q') {
        cout << "Выход из подпрограммы калькулятор..." << endl;
        return;
    }
    cout << "Теперь введите 2 числа через пробел: ";
    cin >> num1 >> num2;

    // --------------------- В switch проверяю введённые знаки и выполняю соответствующие инструкции
    switch (op) {
    case '+':
        cout << "\n Результат суммы: " << num1 + num2 << endl;
        break;
    case '-':
        cout << "\n Результат разности: " << num1 - num2 << endl;
        break;
    case '*':
        cout << "\n Результат умножения: " << num1 * num2 << endl;
        break;
    case '/':
        if (num2 == 0) { // Ноль?
            cout << "\n ❌️ Ошибка: деление на ноль невозможно!" << endl; // Ошибка!
        } else {
            cout << "\n Результат деления: " << num1 / num2 << endl; // Всё в порядке: вывожу результат деления
        }
        break;
    default:
        cout << "\n ❌️ Ошибка: неверный оператор!" << endl;
        break;
    }
}

// =========================================== Подпрограмма конвертер ===========================================
void converter() {
    // Инициализирую 3 переменные для данных
    int choise {}; 
    double temperature {}, result {}; 

    // ---------------------Вывожу приглашение и инструкции к вводу---------------------
    cout << "=============== Конвертер температур ===============" << endl;
    cout << "Введите следующие символы, чтобы выполнить ту или иную операцию:" << endl;
    cout << "> Введите 1, если °C→°F" << "\n" << "> Введите 2, если °F→°C" << "\n" << "> Введите 3, если °C→K" << "\n" << "> Введите 4, если K→°C" << std::endl;
    cin >> choise; // Принимаю выбор варианта меню

    cout << "Пожалуйста, введите значение температуры: "; // Приглашаю ввести значение температуры, а затем его сохраняю
    cin >> temperature;
    cout << endl;

    switch (choise) { // Проверяю значения и выполняю формулы
        case 1:
            cout << "\n" << "Отлично! Переводим из °C в °F." << endl;
            result = temperature * 9.0 / 5.0 + 32.0;
            cout << "Ваша температура в °F = " << result << endl;
            break;
        case 2:
            cout << "\n" << "Отлично! Переводим из °F в °C." << endl;
            result = (temperature - 32.0) * 5.0 / 9.0;
            cout << "Ваша температура в °C = " << result << endl;
            break;
        case 3:
            cout << "\n" << "Отлично! Переводим из °C в K." << endl;
            result = temperature + 273.15;
            cout << "Ваша температура в K = " << result << endl;
            break;
        case 4:
            cout << "\n" << "Отлично! Переводим из K в °C." << endl;
            result = temperature - 273.15;
            cout << "Ваша температура в °C = " << result << endl;
            break;
        default:
            std::cout << "❌️ Ошибка! Вы ввели не верное число варианта выбора перевода температуры!" << std::endl; // Если ввели что-то другое, то выдаю ошибку
            break;
    }
}

